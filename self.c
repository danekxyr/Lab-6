 #include <stdio.h>

int main(void) {
    int h, w;
    
    printf("Enter height and width (2..10): ");
    // Проверяем scanf для двух значений: успешный результат должен быть равен 2
    if (scanf("%d %d", &h, &w) != 2) {
        printf("Input error\n");
        return 1;
    }
    
    // Проверка корректности границ диапазона
    if (h < 2 || h > 10 || w < 2 || w > 10) {
        printf("Range error\n");
        return 1;
    }
    
    // Построение рамки
    for (int row = 1; row <= h; row++) {
        for (int col = 1; col <= w; col++) {
            // Условие границы: первая/последняя строка ИЛИ первый/последний столбец
            if (row == 1 || row == h || col == 1 || col == w) {
                printf("*");
            } else {
                printf(" ");
            }
        }
        printf("\n"); // Конец строки рамки
    }
    
    return 0;
}
